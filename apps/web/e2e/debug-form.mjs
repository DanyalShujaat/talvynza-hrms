import { chromium } from '@playwright/test'
const browser = await chromium.launch()
const page = await browser.newPage()
page.on('pageerror', e => console.log(e.message))
page.on('response', async r => { if (r.request().method() === 'POST' && r.url().includes('/designations')) console.log(r.status(), await r.text()) })
await page.goto('http://localhost:5180/demo')
await page.getByRole('button', { name: 'Enter as administrator' }).click()
await page.waitForURL('http://localhost:5180/')
await page.goto('http://localhost:5180/departments')
await page.getByRole('button', { name: /view/ }).first().click()
await page.getByRole('button', { name: 'Add New Designation' }).click()
await page.getByLabel('Designation', { exact: true }).fill('Test designation')
console.log('before', await page.getByLabel('Designation', { exact: true }).inputValue())
await page.getByRole('button', { name: 'Save', exact: true }).click()
await page.waitForTimeout(1200)
console.log('after', await page.getByRole('dialog').innerText())
await browser.close()
